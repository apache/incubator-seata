    @Test
    public void testExecuteUpdate() throws SQLException {
        String sql = "UPDATE test SET name = 'test' WHERE id = 1";
        when(ExecuteTemplateXA.execute(eq(mockConnectionProxyXA), any(), eq(mockStatement), eq(sql))).thenReturn(1);

        int actualResult = statementProxyXA.executeUpdate(sql);

        assertEquals(1, actualResult);
        StatementCallback<Integer, Statement> capturedCallback = captureStatementCallback(sql);
        // Verify that the captured callback works as expected
        when(mockStatement.executeUpdate(sql)).thenReturn(1);
        int callbackResult = capturedCallback.execute(mockStatement, new Object[]{sql});
        assertEquals(1, callbackResult);
    }

