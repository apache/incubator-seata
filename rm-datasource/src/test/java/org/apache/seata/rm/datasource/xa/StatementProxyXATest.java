    @Test
    public void testExecuteBatch() throws SQLException {
        int[] expectedResult = new int[]{1, 2, 3};
        when(ExecuteTemplateXA.execute(eq(mockConnectionProxyXA), any(), eq(mockStatement))).thenReturn(expectedResult);

        int[] actualResult = statementProxyXA.executeBatch();

        assertEquals(expectedResult, actualResult);
        StatementCallback<int[], Statement> capturedCallback = captureStatementCallback();
        // Verify that the captured callback works as expected
        when(mockStatement.executeBatch()).thenReturn(expectedResult);
        int[] callbackResult = capturedCallback.execute(mockStatement, new Object[]{});
        assertEquals(expectedResult, callbackResult);
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private StatementCallback captureStatementCallback(Object... args) {
        ArgumentCaptor<StatementCallback> statementCallbackCaptor = ArgumentCaptor.forClass(StatementCallback.class);
        mockedStaticExecuteTemplateXA.verify(() -> ExecuteTemplateXA.execute(
                eq(mockConnectionProxyXA),
                statementCallbackCaptor.capture(),
                eq(mockStatement),
                eq(args))
        );
        return statementCallbackCaptor.getValue();
    }

